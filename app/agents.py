
"""Trust, Skeptic, and Leader agents using local Ollama.

Agent explanations are generated by the local LLM.
Agent verdicts are grounded in the PDF evidence checker.
"""

from __future__ import annotations

import json
import os
import re

from dotenv import load_dotenv
from openai import OpenAI

from app.core import Evidence, check_explicit_evidence

load_dotenv()

MODEL = os.getenv("OPENAI_MODEL", "qwen2.5:3b")

ALLOWED_VERDICTS = {
    "supported",
    "contradicted",
    "insufficient_evidence",
}


def _client() -> OpenAI:
    """Connect to the local Ollama OpenAI-compatible endpoint."""
    return OpenAI(
        base_url="http://localhost:11434/v1",
        api_key="ollama",
        timeout=180.0,
        max_retries=1,
    )


def ask_llm(
    system_prompt: str,
    user_prompt: str,
    temperature: float = 0.1,
) -> str:
    """Generate a response using the configured local model."""
    response = _client().chat.completions.create(
        model=MODEL,
        temperature=temperature,
        messages=[
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt},
        ],
    )

    return response.choices[0].message.content or ""


def _parse_json(raw: str) -> dict:
    """Parse a JSON object, including one inside a Markdown code block."""
    cleaned = raw.strip()

    cleaned = re.sub(
        r"^\s*```(?:json)?\s*",
        "",
        cleaned,
        flags=re.IGNORECASE,
    )
    cleaned = re.sub(r"\s*```\s*$", "", cleaned)

    try:
        result = json.loads(cleaned)
    except json.JSONDecodeError:
        start = cleaned.find("{")
        end = cleaned.rfind("}")

        if start < 0 or end <= start:
            raise ValueError("The model did not return valid JSON.")

        result = json.loads(cleaned[start:end + 1])

    if not isinstance(result, dict):
        raise ValueError("Expected a JSON object.")

    return result


def extract_claims(answer: str) -> list[str]:
    """Split an answer into original sentences without rewriting them."""
    from app.core import split_into_claims

    return split_into_claims(answer)


def _parse_evidence(evidence_text: str) -> list[Evidence]:
    """
    Convert the evidence format used by app/main.py into Evidence objects.

    Expected format:
        [Source: test_facts.pdf, page 1]
        The Earth revolves around the Sun.
    """
    if not evidence_text or not evidence_text.strip():
        return []

    passages: list[Evidence] = []
    current_source = "retrieved_pdf"
    current_page = None
    current_lines: list[str] = []

    def save_passage() -> None:
        text = " ".join(
            line.strip()
            for line in current_lines
            if line.strip()
        ).strip()

        if text:
            passages.append(
                Evidence(
                    text=text,
                    source=current_source,
                    page=current_page,
                )
            )

    for line in evidence_text.splitlines():
        line = line.strip()

        if not line:
            continue

        metadata = re.match(
            r"^\[Source:\s*(.*?),\s*page\s*(\d+)\]$",
            line,
            flags=re.IGNORECASE,
        )

        if metadata:
            save_passage()
            current_source = metadata.group(1).strip()
            current_page = int(metadata.group(2))
            current_lines = []
        else:
            current_lines.append(line)

    save_passage()

    return passages


def _evidence_verdict(
    claim: str,
    evidence_text: str,
) -> dict:
    """Determine a verdict using only the supplied PDF passages."""
    passages = _parse_evidence(evidence_text)

    if not passages:
        return {
            "verdict": "insufficient_evidence",
            "explanation": (
                "No usable PDF passages were supplied for this claim."
            ),
            "severity": 0,
            "correction": "",
            "evidence": None,
            "method": "abstain",
        }

    checked = check_explicit_evidence(claim, passages)

    verdict = checked.get("verdict", "insufficient_evidence")

    if verdict not in ALLOWED_VERDICTS:
        verdict = "insufficient_evidence"

    severity_by_verdict = {
        "supported": 0,
        "contradicted": 4,
        "insufficient_evidence": 0,
    }

    return {
        "verdict": verdict,
        "explanation": checked.get("explanation", ""),
        "severity": severity_by_verdict[verdict],
        "correction": "",
        "evidence": checked.get("evidence"),
        "method": checked.get("method", "abstain"),
    }


def _agent_prompt(role: str) -> str:
    """Return role-specific instructions for the explanation."""
    prompts = {
        "Trust": (
            "You are the Trust agent. Examine the claim and quoted PDF "
            "passages. Explain what the passages establish. Distinguish "
            "direct support from a lack of evidence. Never use outside "
            "knowledge or invent facts."
        ),
        "Skeptic": (
            "You are the Skeptic agent. Critically examine whether the "
            "quoted PDF passages actually establish the claim. Look for "
            "a direct conflict in the provided evidence. Do not invent "
            "conflicts or use outside knowledge."
        ),
        "Leader": (
            "You are the Leader agent. Review the claim and the supplied "
            "PDF evidence, along with the earlier agent opinions. Explain "
            "the evidence-based conclusion. Do not use majority voting, "
            "outside knowledge, or unsupported assumptions. If evidence "
            "is inadequate, say so."
        ),
    }

    if role not in prompts:
        raise ValueError(f"Unknown agent role: {role}")

    return prompts[role]


def run_agent(
    role: str,
    claim: str,
    evidence: str,
    previous_opinions: str = "",
) -> dict:
    """
    Run an agent and return a PDF-grounded verdict.

    The local LLM supplies a role-specific explanation. The final verdict
    is constrained by the existing explicit-evidence checker so the model
    cannot override that check with unsupported outside knowledge.
    """
    if role not in {"Trust", "Skeptic", "Leader"}:
        raise ValueError(f"Unknown agent role: {role}")

    checked = _evidence_verdict(claim, evidence)

    user_prompt = f"""
CLAIM:
{claim}

PDF PASSAGES:
{evidence or "[No passages retrieved]"}

PREVIOUS AGENT OPINIONS:
{previous_opinions or "[No previous opinions]"}

The evidence-checker's current result is:
{checked["verdict"]}

Evidence-check explanation:
{checked["explanation"]}

Write a concise explanation of what the supplied passages establish.
Do not use general knowledge.
Do not invent evidence, sources, or quotations.
Do not change the claim.
If the passages do not establish a fact, acknowledge that limitation.

Return only JSON in this format:
{{
  "explanation": "A concise explanation grounded in the supplied passages.",
  "correction": ""
}}
"""

    try:
        raw = ask_llm(
            system_prompt=_agent_prompt(role),
            user_prompt=user_prompt,
            temperature=0.0,
        )
        result = _parse_json(raw)

        explanation = str(result.get("explanation", "")).strip()
        correction = str(result.get("correction", "")).strip()

    except Exception:
        # Keep verification available even if the local model response
        # is malformed or Ollama temporarily fails.
        explanation = checked["explanation"]
        correction = ""

    # The deterministic checker, not the LLM's free-form opinion,
    # controls the verdict.
    return {
        "verdict": checked["verdict"],
        "explanation": explanation or checked["explanation"],
        "severity": checked["severity"],
        "correction": correction,
        "evidence": checked["evidence"],
        "method": checked["method"],
    }
